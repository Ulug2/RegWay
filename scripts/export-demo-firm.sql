-- Run by scripts/export-demo-firm.sh. Reads one firm from the source
-- database and prints SQL that recreates it in a local database. Read-only:
-- the whole script runs in a read-only transaction.
--
-- Never copied: sign-in accounts, firm members, chat conversations, usage and
-- rate-limit records, queued profile changes. The printed file creates its
-- own local-only demo user instead.

\set ON_ERROR_STOP on
begin transaction read only;

select id as firm_id from firms where name ilike :'firm' \gset

-- The demo user every exported flag and note is re-attributed to.
\set demo_user 00000000-0000-4000-8000-00000000d3a0

\echo '-- Generated by scripts/export-demo-firm.sh. Do not edit by hand; run the'
\echo '-- script again instead. Loaded into LOCAL databases only, after seed.sql,'
\echo '-- by `supabase start` and `supabase db reset` (supabase/config.toml).'
\echo '--'
select '-- Firm: ' || name || '. Exported ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI') || ' UTC.' from firms where id = :'firm_id';
\echo '--'
\echo '-- Sign in locally with  demo@regway.local  /  regway-demo-local'
\echo ''
\echo 'do $guard$'
\echo 'begin'
\echo '  if exists (select 1 from vault.secrets where name = ''service_role_key'') then'
\echo '    raise exception ''demo-firm.sql is for local databases only'';'
\echo '  end if;'
\echo 'end $guard$;'
\echo ''

-- A local sign-in account. The password is public on purpose: it opens
-- nothing but a database on the developer's own machine.
select format($f$insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', %1$L, 'authenticated', 'authenticated',
  'demo@regway.local', extensions.crypt('regway-demo-local', extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '')
on conflict (id) do nothing;
insert into auth.identities (id, user_id, provider_id, provider, identity_data, created_at, updated_at, last_sign_in_at)
values (gen_random_uuid(), %1$L, %1$L, 'email',
  jsonb_build_object('sub', %1$L, 'email', 'demo@regway.local', 'email_verified', true), now(), now(), now())
on conflict (provider_id, provider) do nothing;
$f$, :'demo_user');

-- Each table as one statement: the rows travel as JSON and are turned back
-- into rows by column name, so the file does not depend on column order.
\set fmt 'insert into public.%1$I select * from jsonb_populate_recordset(null::public.%1$I, %2$L::jsonb) on conflict do nothing;'

with rows as (select to_jsonb(x) as j from firms x where id = :'firm_id')
select format(:'fmt', 'firms', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

with rows as (select to_jsonb(x) as j from funds x where firm_id = :'firm_id')
select format(:'fmt', 'funds', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

-- Logos point at the hosted project's storage; a local copy shows initials.
with rows as (select to_jsonb(x) || '{"logo_url": null}' as j from portfolio_companies x where firm_id = :'firm_id')
select format(:'fmt', 'portfolio_companies', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

with rows as (select to_jsonb(x) as j from fund_holdings x where firm_id = :'firm_id')
select format(:'fmt', 'fund_holdings', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

-- The documents this firm is shown (matches the matcher rejected are left
-- out), plus the other versions of the same development.
with shown as (
  select distinct regulation_id as id from regulation_relevance
  where firm_id = :'firm_id' and coalesce(relevance_reason, '') not like 'NOT_RELEVANT:%'
), wanted as (
  select id from shown
  union select r.duplicate_of from regulations r join shown s on s.id = r.id where r.duplicate_of is not null
  union select r.id from regulations r join shown s on s.id = r.duplicate_of
), rows as (
  select to_jsonb(x) as j from regulations x join wanted w on w.id = x.id
)
select format(:'fmt', 'regulations', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

with rows as (
  select to_jsonb(x) as j from regulation_relevance x
  where firm_id = :'firm_id' and coalesce(relevance_reason, '') not like 'NOT_RELEVANT:%'
)
select format(:'fmt', 'regulation_relevance', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

with rows as (
  select to_jsonb(x) as j from regulation_impacts x
  where firm_id = :'firm_id' and regulation_id in (
    select regulation_id from regulation_relevance
    where firm_id = :'firm_id' and coalesce(relevance_reason, '') not like 'NOT_RELEVANT:%')
)
select format(:'fmt', 'regulation_impacts', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

with rows as (
  select distinct on (regulation_id) to_jsonb(x) || jsonb_build_object('user_id', :'demo_user') as j
  from regulation_flags x where firm_id = :'firm_id' order by regulation_id, flagged_at
)
select format(:'fmt', 'regulation_flags', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

with rows as (
  select to_jsonb(x) || jsonb_build_object('user_id', :'demo_user') as j from regulation_notes x where firm_id = :'firm_id'
)
select format(:'fmt', 'regulation_notes', coalesce(jsonb_agg(j), '[]'::jsonb)::text) from rows;

select format('insert into public.firm_members (user_id, firm_id) values (%L, %L) on conflict do nothing;', :'demo_user', :'firm_id');

-- Make the copy behave like a firm in use today.
\echo ''
\echo '-- The dashboard opens on what was matched today, so move every match'
\echo '-- forward by the same amount until the newest one is a minute old.'
select format('update public.regulation_relevance set created_at = created_at + (now() - interval ''1 minute'' - (select max(created_at) from public.regulation_relevance where firm_id = %1$L)) where firm_id = %1$L;', :'firm_id');
\echo '-- A company scanned over a week ago is scanned again when the dashboard'
\echo '-- opens, which needs an AI key. Mark them all as just scanned.'
select format('update public.portfolio_companies set last_scanned_at = now() where firm_id = %L;', :'firm_id');

rollback;
